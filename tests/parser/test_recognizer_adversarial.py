# CRITICAL FINDING 1 -- hand-written .gle must never overwrite a user's file
# --------------------------------------------------------------------------- #


def _md5(path: Path) -> str:
    import hashlib

    return hashlib.md5(path.read_bytes()).hexdigest()


def test_critical1_handwritten_gle_does_not_overwrite_user_datafile(tmp_path):
    """Reviewer's exact repro: a hand-written .gle with NO gleplot metadata
    block references 'results_2024.dat' -- an ordinary user file whose name
    happens to match the old sidecar heuristic. Parsing then re-saving to the
    SAME path must leave the referenced data file byte-for-byte UNCHANGED (the
    header must not be corrupted, e.g. 'Temperature (K) Resistance (Ohm)'
    silently truncated to 'Temperature (K)').
    """
    dat_content = (
        "Temperature (K) Resistance (Ohm)\n" "1.0 100.0\n" "2.0 200.0\n" "3.0 300.0\n"
    )
    src = (
        "size 20.32 15.24\n"
        "begin graph\n"
        "   data results_2024.dat d1=c1,c2\n"
        "   d1 line color blue lwidth 0.05\n"
        "end graph\n"
    )
    gle = _write(tmp_path, "hand.gle", src, {"results_2024.dat": dat_content})
    dat_path = tmp_path / "results_2024.dat"

    before = _md5(dat_path)
    rec = parse_gle_figure(gle)

    # The reference is treated as an external file reference (NOT adopted as an
    # editable import), so nothing pulls the file's header into column_names.
    ax = rec.figure.axes_list[0]
    assert ax.lines == []
    assert len(ax.file_series) == 1
    assert ax.file_series[0]["data_file"] == "results_2024.dat"

    # Re-save to the SAME .gle path; the referenced data file must be untouched.
    rec.figure.savefig_gle(str(gle))
    after = _md5(dat_path)
    assert before == after, "user's data file was silently rewritten by savefig_gle"
    # Belt-and-braces: the multi-word header survived verbatim.
    assert dat_path.read_text() == dat_content


