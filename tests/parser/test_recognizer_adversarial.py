        "size 10 8\n"
        "begin graph\n"
        "   size 10 8\n"
        '   xtitle "X"\n'
        '   ytitle "Y"\n'
        "   xaxis min 0 max 3000\n"
        "   yaxis min 0 max 1\n"
        "end graph\n"
        "set hei 0.7\n"
        "set just left\n"
        "amove xg(40) yg(0.34)\n"
        'write "beta"\n'
        "set just left\n"
        "amove xg(40) yg(0.09)\n"
        'write "alpha"\n'
